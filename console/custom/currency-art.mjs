export function currencyIconPath(id) {
  return Object.hasOwn(CurrencyArt, id) ? CurrencyArt[id] : DefaultCurrencyArt;
}

export function setCurrencyLabel(element, id, name) {
  const icon = document.createElement('img');
  icon.className = 'cardgame-currency-icon'; icon.alt = ''; icon.setAttribute('aria-hidden', 'true');
  icon.width = 24; icon.height = 24; icon.loading = 'lazy'; icon.src = currencyIconPath(id);
  icon.addEventListener('error', () => { if (icon.getAttribute('src') !== DefaultCurrencyArt) icon.src = DefaultCurrencyArt; }, { once: true });
  const label = document.createElement('span'); label.textContent = name;
  element.classList.add('cardgame-currency-label'); element.replaceChildren(icon, label);
}
